#!/usr/bin/env python3
"""
Turn original photos into small, fast web versions served from this repo.

  python3 tools/optimize_images.py /path/to/originals

What it does
  * Reads index.html to find every Google Drive image ID the site uses
    (film / digital / stills photos, album covers, wedding video thumbnails).
  * Finds the matching original in the folder you pass (searched recursively),
    by filename (tools/image-ids.json maps Drive ID -> original filename).
  * Writes resized WebP copies to img/p/<id>-<width>.webp, strips camera
    metadata (GPS etc.), keeps the colour profile, and makes a tiny blurred
    preview used as a placeholder while the real image streams in.
  * Writes img/manifest.js, which the site reads. Any ID missing from the
    manifest keeps loading from Google Drive, so a partial run is safe.

Re-running only converts images that are new or changed.
"""
import base64, hashlib, io, json, os, re, sys
from PIL import Image, ImageOps

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HTML = os.path.join(ROOT, 'index.html')
OUT_DIR = os.path.join(ROOT, 'img', 'p')
MANIFEST = os.path.join(ROOT, 'img', 'manifest.js')
ID_MAP = os.path.join(ROOT, 'tools', 'image-ids.json')
STATE = os.path.join(ROOT, 'tools', '.image-state.json')

WIDTHS = {
    'photo':  [480, 960, 1600, 2400],
    'cover':  [300, 600, 1000],
    'vthumb': [640, 1280],
}
QUALITY = 80
EXTS = ('.jpg', '.jpeg', '.png', '.webp', '.tif', '.tiff', '.heic')


def ids_in_site():
    s = open(HTML, encoding='utf-8').read()
    roles = {}
    names = {}
    # photos and album covers live in content/content.js (written by /admin)
    content_path = os.path.join(ROOT, 'content', 'content.js')
    if os.path.exists(content_path):
        raw = open(content_path, encoding='utf-8').read()
        c = json.loads(raw[raw.index('SITE_CONTENT =') + len('SITE_CONTENT ='):].strip().rstrip(';'))
        for cat in ('film', 'digital', 'stills'):
            for p in c.get('photos', {}).get(cat, []):
                roles[p['id']] = 'photo'
                names[p['id']] = p.get('file', '')
        for a in c.get('music', []):
            if a.get('coverId'):
                roles.setdefault(a['coverId'], 'cover')
        for v in c.get('videos', []):
            if v.get('thumbId'):
                roles.setdefault(v['thumbId'], 'vthumb')
    for i in re.findall(r"driveThumb\('([A-Za-z0-9_-]{20,})',\s*\d+\)", s):
        roles.setdefault(i, 'cover')
    for i in re.findall(r"driveThumbId:'([A-Za-z0-9_-]{20,})'", s):
        roles.setdefault(i, 'vthumb')
    for i in re.findall(r'drive\.google\.com/thumbnail\?id=([A-Za-z0-9_-]{20,})', s):
        roles.setdefault(i, 'photo')
    return roles, names


def load_json(path, default):
    try:
        with open(path, encoding='utf-8') as f:
            return json.load(f)
    except (OSError, ValueError):
        return default


def index_originals(folder):
    found = {}
    for dp, _, files in os.walk(folder):
        for fn in files:
            if fn.startswith('.'):
                continue
            # Drive sometimes downloads files without an extension, so index every
            # file by full name and by name-minus-extension; only matches get opened.
            found.setdefault(fn.lower(), os.path.join(dp, fn))
            if fn.lower().endswith(EXTS):
                found.setdefault(os.path.splitext(fn)[0].lower(), os.path.join(dp, fn))
    return found


def file_hash(path):
    h = hashlib.sha1()
    with open(path, 'rb') as f:
        for chunk in iter(lambda: f.read(1 << 20), b''):
            h.update(chunk)
    return h.hexdigest()


def convert(src, file_id, widths):
    im = Image.open(src)
    im = ImageOps.exif_transpose(im)
    icc = im.info.get('icc_profile')
    if im.mode not in ('RGB', 'RGBA'):
        im = im.convert('RGBA' if 'A' in im.getbands() else 'RGB')
    w0, h0 = im.size
    made = []
    for w in widths:
        if w > w0 and made:
            break
        tw = min(w, w0)
        th = round(h0 * tw / w0)
        r = im if tw == w0 else im.resize((tw, th), Image.LANCZOS)
        out = os.path.join(OUT_DIR, '%s-%d.webp' % (file_id, w))
        kw = dict(quality=QUALITY, method=6)
        if icc:
            kw['icc_profile'] = icc
        r.save(out, 'WEBP', **kw)
        made.append(w)
    # tiny blurred preview, inlined into the manifest
    t = im.copy()
    t.thumbnail((24, 24))
    buf = io.BytesIO()
    t.convert('RGB').save(buf, 'WEBP', quality=40)
    lqip = 'data:image/webp;base64,' + base64.b64encode(buf.getvalue()).decode()
    return {'w': made, 'r': round(w0 / h0, 4), 'b': lqip}


def write_manifest(entries):
    os.makedirs(os.path.dirname(MANIFEST), exist_ok=True)
    body = json.dumps(entries, separators=(',', ':'), sort_keys=True)
    with open(MANIFEST, 'w', encoding='utf-8') as f:
        f.write('/* generated by tools/optimize_images.py, do not edit */\n')
        f.write('window.IMG_MANIFEST=' + body + ';\n')


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        sys.exit(1)
    folder = sys.argv[1]
    os.makedirs(OUT_DIR, exist_ok=True)
    roles, names = ids_in_site()
    id_map = load_json(ID_MAP, {})
    id_map.update({k: v for k, v in names.items() if k not in id_map})
    with open(ID_MAP, 'w', encoding='utf-8') as f:
        json.dump(id_map, f, indent=1, sort_keys=True)
    state = load_json(STATE, {})
    originals = index_originals(folder)

    manifest = {}
    raw = open(MANIFEST, encoding='utf-8').read() if os.path.exists(MANIFEST) else ''
    m = re.search(r'window\.IMG_MANIFEST=(\{.*\});', raw, re.S)
    if m:
        manifest = json.loads(m.group(1))

    done = skipped = 0
    missing = []
    for file_id, role in sorted(roles.items()):
        name = id_map.get(file_id)
        src = None
        for key in filter(None, [name and name.lower(), name and os.path.splitext(name)[0].lower(), file_id.lower()]):
            if key in originals:
                src = originals[key]
                break
        if not src:
            if file_id not in manifest:
                missing.append((file_id, role, name))
            continue
        h = file_hash(src)
        if state.get(file_id) == h and file_id in manifest:
            skipped += 1
            continue
        manifest[file_id] = convert(src, file_id, WIDTHS[role])
        state[file_id] = h
        done += 1
        print('ok  %-6s %s  <- %s' % (role, file_id, os.path.relpath(src, folder)))

    write_manifest(manifest)
    with open(STATE, 'w', encoding='utf-8') as f:
        json.dump(state, f, indent=1, sort_keys=True)
    print('\nconverted %d, unchanged %d, in manifest %d of %d' % (done, skipped, len(manifest), len(roles)))
    if missing:
        print('\nno original found for %d (these keep loading from Drive):' % len(missing))
        for file_id, role, name in missing:
            print('  %-6s %s  %s' % (role, file_id, name or '(name unknown: add it to tools/image-ids.json)'))


if __name__ == '__main__':
    main()
